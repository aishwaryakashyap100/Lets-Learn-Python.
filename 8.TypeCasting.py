# Typecasting is the conversion of one data type into the other data type

a = "5"
b = "9"
print(int(a)+int(b)) # If we are converting any data type then it should be valid

# Typecasting is of two types explicit and implicit

# Implicit - done by the python
one = 3.9
two = 7
print(one+two)

# Explicit - done by the programmer
c = '4'
d = 3
print("The sum of both the numbers is :",int(c)+d)