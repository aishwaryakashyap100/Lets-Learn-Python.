a = 1 # This is integer data type
print(a)

b = 1.7 # This is float data type
print(b)

c = "Hello" # This is string data type
print(c)

d = True # This is boolean data type
print(d)

e = [4,6,7,['five', 'eight']] # This is list data type
print(e)

f = (7,9,('hello')) # This is tuple data type
print(f)

g = {"name":"Aishwarya", "age":18} # This is dictionary data type
print(g)

# This are all the data types in python