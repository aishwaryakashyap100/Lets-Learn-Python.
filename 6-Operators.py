# Python have different types of operators

addition = 15+7
print(addition)

subtraction = 15-7
print(subtraction)

multiplication = 15*7
print(multiplication)

division = 15/7
print(division)

modulus = 15%7 
print(modulus)

floordivision = 15//7
print(floordivision)

exponential = 15**7
print(exponential)